"""Generate python/matplotlib_rs/_doc_cache.py.

matplotlib builds the ``set()`` signature and property docs of every Artist
class at import time by introspecting all setters (``ArtistInspector``),
which costs ~100 ms per import.  The results for matplotlib_rs' own classes
are fixed, so they are computed once here.  Re-run after changing or
re-vendoring any Artist class (tests/unit/test_doc_cache.py checks it).
"""
import os
import pathlib
import pprint
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "python"))
os.environ["MPLRS_NO_DOC_CACHE"] = "1"

import matplotlib_rs  # noqa: E402
matplotlib_rs.install()
import matplotlib.pyplot  # noqa: E402,F401
import matplotlib.artist as martist  # noqa: E402
import mpl_toolkits.mplot3d  # noqa: E402,F401
import mpl_toolkits.axes_grid1  # noqa: E402,F401
import mpl_toolkits.axisartist  # noqa: E402,F401
import matplotlib.tri  # noqa: E402,F401
import matplotlib.animation  # noqa: E402,F401
import matplotlib.widgets  # noqa: E402,F401
import matplotlib.sankey  # noqa: E402,F401


def all_classes():
    seen = set()
    stack = [martist.Artist]
    while stack:
        c = stack.pop()
        if c in seen:
            continue
        seen.add(c)
        stack.extend(c.__subclasses__())
    def reachable(c):
        # only classes defined in a module body (not made by class factories,
        # whose names users' factories could reuse)
        obj = sys.modules.get(c.__module__)
        for part in c.__qualname__.split("."):
            obj = getattr(obj, part, None)
        return obj is c

    return sorted((c for c in seen if c.__module__.startswith("matplotlib_rs") and reachable(c)),
                  key=lambda c: (c.__module__, c.__qualname__))


def main():
    docs = {}
    for cls in all_classes():
        docs[(cls.__module__, cls.__qualname__)] = (
            martist.kwdoc(cls), martist.ArtistInspector(cls).get_setters())
    out = ROOT / "python" / "matplotlib_rs" / "_doc_cache.py"
    out.write_text(
        '"""Precomputed Artist property docs (generated by tools/gen_doc_cache.py;\n'
        'do not edit)."""\n\nDOCS = ' + pprint.pformat(docs, width=100) + "\n")
    print(f"wrote {len(docs)} classes to {out}")


if __name__ == "__main__":
    main()
